CS_MONTH_ABBR = ("led", "úno", "bře", "dub", "kvě", "čvn",
                 "čvc", "srp", "zář", "říj", "lis", "pro")


DE_MONTH_ABBR = ("Jan", "Feb", "Mär", "Apr", "Mai", "Jun",
                 "Jul", "Aug", "Sep", "Okt", "Nov", "Dez")


def decimal_char(lang: str) -> str:
    return "," if lang in DECIMAL_COMMA else "."


def date_format(lang: str) -> str:
    """strftime / Plotly format of a date: day.month.year for cs and de, ISO for en."""
    return "%d.%m.%Y" if lang in ("cs", "de") else "%Y-%m-%d"


def date_picker_format(lang: str) -> str:
    """The same date format in the notation of the date picker (moment.js)."""
    return "DD.MM.YYYY" if lang in ("cs", "de") else "YYYY-MM-DD"


def t(key: str, lang: str) -> str:
    table = STRINGS.get(lang, STRINGS["en"])
    return table.get(key, STRINGS["en"].get(key, key))


def tn(key: str, lang: str, n: int) -> str:
    """``key`` for one item, ``key_n`` (when there is one) for several."""
    if n > 1 and f"{key}_n" in STRINGS["en"]:
        return t(f"{key}_n", lang)
    return t(key, lang)


def method_title(key: str, n_producers: int, lang: str) -> str:
    """Title of a method's column: the exact method and the replay say when several
    producers were shared as one pool (the page and the export use the same text)."""
    if n_producers > 1 and f"{key}_pool" in STRINGS["en"]:
        return t(f"{key}_pool", lang).format(n=n_producers)
    return t(key, lang)


def month_label(ts: pd.Timestamp, lang: str) -> str:
    if lang == "cs":
        return f"{CS_MONTH_ABBR[ts.month - 1]} {ts.year}"
    if lang == "de":
        return f"{DE_MONTH_ABBR[ts.month - 1]} {ts.year}"
    return ts.strftime("%b %Y")


def fmt_num(x: float | None, lang: str, decimals: int = 0) -> str:
    """Thousands-separated number; Czech uses a thin space and a decimal comma, German a
    point and a decimal comma."""
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "—"
    s = f"{x:,.{decimals}f}"
    if lang == "cs":
        s = s.replace(",", " ").replace(".", ",")
    elif lang == "de":
        s = s.replace(",", "\0").replace(".", ",").replace("\0", ".")
    return s


def fmt_pct(x: float | None, lang: str, decimals: int = 1) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "—"
    return f"{fmt_num(x, lang, decimals)} %"


def fmt_date(ts: pd.Timestamp | None, lang: str) -> str:
    if ts is None or pd.isna(ts):
        return "—"
    return ts.strftime(date_format(lang))


def plotly_separators(lang: str) -> str:
    """Plotly ``layout.separators``: decimal char then thousands char."""
    return {"cs": ", ", "de": ",."}.get(lang, ".,")


def fmt_duration(seconds: float, lang: str) -> str:
    """Human duration: µs below 1 ms, ms below 1 s, else s."""
    if seconds < 1e-3:
        return f"{fmt_num(seconds * 1e6, lang, 2)}\u00a0µs"
    if seconds < 1:
        return f"{fmt_num(seconds * 1e3, lang, 1)}\u00a0ms"
    return f"{fmt_num(seconds, lang, 2)}\u00a0s"


def fmt_signed(x: float, lang: str, decimals: int = 1) -> str:
    sign = "+" if x > 0 else ("−" if x < 0 else "±")
    return f"{sign}{fmt_num(abs(x), lang, decimals)}"
